//! Розмова між ядром-сервісом і його клієнтами.
//!
//! Ядро живе окремим процесом і тримає завдання. CLI, вікно й native
//! messaging host — рівноправні клієнти: усі троє говорять **одним**
//! протоколом через локальний канал.
//!
//! Це головна архітектурна межа проєкту. Через неї:
//!
//! * вікно можна закрити, і завантаження триватимуть — у треї лишається
//!   ядро на кілька десятків мегабайтів, а не гроно процесів WebView2;
//! * крах або оновлення UI не чіпає активних завдань;
//! * зовнішні плагіни-протоколи отримають той самий транспорт, що й UI,
//!   тобто контракт лишиться один, а не два.
//!
//! # Безпека каналу
//!
//! Канал **локальний і лише локальний**: named pipe на Windows, unix-сокет
//! на решті систем. Жодного TCP-порту, навіть на `127.0.0.1`.
//!
//! Це не педантизм. Локальний HTTP-сервіс із токеном — рівно та схема, на
//! якій pyLoad отримав pre-auth RCE (CVE-2023-0297), а gopeed змушує людину
//! вручну вводити порт і токен, через що перехоплення з браузера часто
//! просто не працює. Named pipe знімає обидві проблеми: його не видно
//! ззовні машини, і налаштовувати нічого не треба.

