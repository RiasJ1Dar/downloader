//! Файловий журнал із ротацією за розміром.
//!
//! Ядро живе в треї й запускається з автозапуску — без консолі. Доти журнал
//! ішов лише в `stderr`, тобто в нікуди: коли в людини щось не качалося,
//! подивитися не було куди взагалі. Питання «чому не працює» не мало відповіді
//! навіть у розробника, бо відтворити чужий випадок без слідів неможливо.
//!
//! Тому пишемо **завжди**, а не за ключем: ключ, який треба знати заздалегідь,
//! не допомагає тому, у кого вже зламалося.
//!
//! Ротація проста навмисно: один активний файл і кілька попередніх. Складніша
//! (за датою, стисненням) потребувала б залежності, а тут важливо лише не
//! з'їсти диск.

use std::fs::{self, File, OpenOptions};
use std::io::{self, Write};
use std::path::{Path, PathBuf};
use std::sync::{Arc, Mutex};

/// Скільки важить файл, перш ніж його відкладуть у `.1`.
const МЕЖА_БАЙТІВ: u64 = 5 * 1024 * 1024;

/// Скільки попередніх файлів тримати (`.1` … `.N`).
const СКІЛЬКИ_ЗБЕРІГАТИ: usize = 3;

/// Куди писати журнал для цієї теки даних.
#[must_use]
pub fn файл_журналу(тека_даних: &Path) -> PathBuf {
    тека_даних.join("logs").join("downloader-core.log")
}

/// Той, хто пише в файл і вчасно його відкладає.
///
/// `Clone` дешевий: усі копії пишуть в один файл під спільним замком, інакше
/// рядки з різних потоків перемішалися б усередині одного рядка.
#[derive(Clone)]
pub struct Журнал {
    стан: Arc<Mutex<Стан>>,
}

struct Стан {
    шлях: PathBuf,
    файл: File,
    написано: u64,
}

impl Журнал {
    /// Відкрити (або створити) журнал за шляхом.
    ///
    /// # Помилки
    ///
    /// Якщо теку не вдалося створити або файл не відкривається на запис.
    pub fn відкрити(шлях: &Path) -> io::Result<Self> {
        if let Some(тека) = шлях.parent() {
            fs::create_dir_all(тека)?;
        }
        let файл = OpenOptions::new().create(true).append(true).open(шлях)?;
        let написано = файл.metadata().map(|m| m.len()).unwrap_or(0);

        Ok(Self {
            стан: Arc::new(Mutex::new(Стан {
                шлях: шлях.to_path_buf(),
                файл,
                написано,
            })),
        })
    }
}

impl Write for Журнал {
    fn write(&mut self, буфер: &[u8]) -> io::Result<usize> {
        // Отруєний замок не має глушити програму: журнал — не те, заради чого
        // варто падати. Але й мовчки губити рядки не можна, тому помилка йде
        // назад викликачеві, а він вирішує.
        let mut стан = self
            .стан
            .lock()
            .map_err(|_| io::Error::other("замок журналу отруєно"))?;

        let записано = стан.файл.write(буфер)?;
        стан.написано += записано as u64;

        if стан.написано >= МЕЖА_БАЙТІВ {
            перекласти(&mut стан)?;
        }
        Ok(записано)
    }

    fn flush(&mut self) -> io::Result<()> {
        let mut стан = self
            .стан
            .lock()
            .map_err(|_| io::Error::other("замок журналу отруєно"))?;
        стан.файл.flush()
    }
}

/// Відкласти поточний файл і почати новий.
fn перекласти(стан: &mut Стан) -> io::Result<()> {
    стан.файл.flush()?;

    // Найстаріший іде геть, решта зсуваються: .2 → .3, .1 → .2, активний → .1.
    let з_номером = |n: usize| стан.шлях.with_extension(format!("log.{n}"));
    let найстаріший = з_номером(СКІЛЬКИ_ЗБЕРІГАТИ);
    if найстаріший.exists() {
        fs::remove_file(&найстаріший)?;
    }
    for n in (1..СКІЛЬКИ_ЗБЕРІГАТИ).rev() {
        let звідки = з_номером(n);
        if звідки.exists() {
            fs::rename(&звідки, з_номером(n + 1))?;
        }
    }
    fs::rename(&стан.шлях, з_номером(1))?;

    стан.файл = OpenOptions::new()
        .create(true)
        .append(true)
        .open(&стан.шлях)?;
    стан.написано = 0;
    Ok(())
}

#[cfg(test)]
#[allow(
    clippy::expect_used,
    clippy::unwrap_used,
    clippy::panic,
    reason = "у тестах падіння і є повідомленням про помилку"
)]
mod tests {
    use super::*;

    fn тимчасова_тека(мітка: &str) -> PathBuf {
        let унікальне = std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .map(|d| d.as_nanos())
            .unwrap_or(0);
        let тека = std::env::temp_dir().join(format!("dl-журнал-{мітка}-{унікальне}"));
        fs::create_dir_all(&тека).expect("тимчасова тека");
        тека
    }

    #[test]
    fn шлях_журналу_лежить_у_теці_даних() {
        let шлях = файл_журналу(Path::new(r"C:\dane"));
        assert!(шлях.ends_with("logs/downloader-core.log") || шлях.ends_with(r"logs\downloader-core.log"));
    }

    #[test]
    fn рядки_потрапляють_у_файл() {
        let тека = тимчасова_тека("запис");
        let шлях = тека.join("x.log");
        let mut ж = Журнал::відкрити(&шлях).expect("відкрити");
        ж.write_all(b"privet\n").expect("запис");
        ж.flush().expect("скид");

        let вміст = fs::read_to_string(&шлях).expect("читання");
        assert!(вміст.contains("privet"), "у файлі: {вміст}");
        fs::remove_dir_all(&тека).ok();
    }

    /// Журнал не має з'їдати диск на машині, яка працює місяцями.
    #[test]
    fn переповнений_файл_відкладається_а_новий_починається_з_нуля() {
        let тека = тимчасова_тека("ротація");
        let шлях = тека.join("y.log");
        let mut ж = Журнал::відкрити(&шлях).expect("відкрити");

        let шматок = vec![b'x'; 1024];
        let скільки = (МЕЖА_БАЙТІВ / 1024) + 2;
        for _ in 0..скільки {
            ж.write_all(&шматок).expect("запис");
        }
        ж.flush().expect("скид");

        let відкладений = шлях.with_extension("log.1");
        assert!(відкладений.exists(), "попередній файл не відклали");

        let активний = fs::metadata(&шлях).expect("активний файл").len();
        assert!(
            активний < МЕЖА_БАЙТІВ,
            "після ротації активний файл має бути малим, а він {активний} Б"
        );
        fs::remove_dir_all(&тека).ok();
    }
}
