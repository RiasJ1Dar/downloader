//! Помилки ядра.
//!
//! Правило проєкту: помилку або обробляють, або про неї гучно кажуть.
//! Мовчазний fallback ховає слід і коштує днів на пошук.

use std::path::PathBuf;

/// Помилка, яку ядро віддає назовні.
#[derive(Debug, thiserror::Error)]
pub enum Error {
    /// Сервер не тримає `Range` — качати можна лише в один потік.
    #[error("сервер не підтримує Range: {url}")]
    RangeUnsupported { url: String },

    /// Ресурс на сервері змінився між спробами: `If-Range` дав 200 замість 206.
    ///
    /// Докачувати не можна — склейка шматків двох версій дає **тихо
    /// зіпсований файл**. Тільки з нуля.
    #[error("ресурс змінився під час завантаження, докачування неможливе: {url}")]
    ResourceChanged { url: String },

    /// Завантажене не збіглося з очікуваним розміром або хешем.
    #[error("перевірка не пройдена для {path}: очікували {expected}, маємо {actual}")]
    VerificationFailed {
        path: PathBuf,
        expected: String,
        actual: String,
    },

    /// Звернення до сегмента, якого в таблиці немає.
    #[error("сегмент {id} не існує, у таблиці їх {count}")]
    SegmentOutOfBounds { id: usize, count: usize },

    /// Воркер спробував записати за межу свого сегмента.
    ///
    /// Це не гранична ситуація, а **баг**: значить, він пише в чужий
    /// діапазон. Мовчазне обрізання тут дало б биті дані без сліду.
    #[error("сегмент {id} (діапазон {start}..{end}) спробував дописати до {attempted}")]
    SegmentOverrun {
        id: usize,
        start: u64,
        end: u64,
        attempted: u64,
    },

    /// Таблиця сегментів не покриває файл суцільно.
    ///
    /// Найчастіше — зіпсований або застарілий файл стану. Продовжувати не
    /// можна: склейка по такій таблиці дає файл із дірками.
    #[error("таблиця сегментів пошкоджена: {reason}")]
    SegmentCoverageBroken { reason: String },

    /// Помилка сховища завдань.
    ///
    /// Текст іде від SQLite і призначений для журналу: людині показуємо те,
    /// що вище рівнем, а тут потрібна точна причина для розбору.
    #[error("сховище: {0}")]
    Store(String),

    /// Сервер вимагає вхід (401/403). Без пароля й cookie в тексті.
    #[error("потрібна авторизація (HTTP {status}): {url}")]
    AuthRequired { url: String, status: u16 },

    #[error("помилка вводу-виводу: {0}")]
    Io(#[from] std::io::Error),
}

/// Результат операції ядра.
pub type Result<T> = std::result::Result<T, Error>;
