//! ffmpeg: знайти й попросити зробити дві речі.
//!
//! # Навіщо окремий крейт
//!
//! ffmpeg потрібен трьом модулям одразу: yt-dlp зводить ним відео зі звуком,
//! HLS міняє контейнер склеєного потоку, DASH зводить окремі доріжки. Пошук
//! бінарника в кожному з них означав би три копії однієї логіки, які
//! розійдуться на першій же правці.
//!
//! # Чого тут немає
//!
//! Перекодування. Обидва виклики йдуть із `-c copy`: контейнер міняється,
//! потік лишається байт у байт. Перекодування — це години процесорного часу
//! й втрата якості, і жоден із наших випадків його не потребує.

use std::path::{Path, PathBuf};

use tokio::process::Command;

/// Що пішло не так.
#[derive(Debug, thiserror::Error)]
pub enum Помилка {
    /// ffmpeg не знайдено ні поруч із програмою, ні в PATH.
    #[error("ffmpeg не знайдено: поставте його командою `dl ffmpeg-install`")]
    Немає,

    /// ffmpeg запустився, але зробити не зміг.
    #[error("ffmpeg не впорався: {0}")]
    Відмова(String),

    /// Не вдалося запустити процес.
    #[error("не запустити ffmpeg: {0}")]
    Запуск(String),
}

type Результат<T> = std::result::Result<T, Помилка>;

/// Чи є ffmpeg у системі.
#[must_use]
pub fn є() -> bool {
    знайти().is_some()
}

/// Де лежить ffmpeg: спершу поруч із програмою, потім у PATH.
///
/// ⚠️ Порядок не випадковий. Поруч лежить **наш** ffmpeg — LGPL-збірка
/// відомої версії, яку поклав інсталятор. Чужий із PATH може виявитись чим
/// завгодно: старим, зібраним без потрібних форматів, або взагалі іншою
/// програмою з таким іменем.
#[must_use]
pub fn знайти() -> Option<PathBuf> {
    let поруч = std::env::current_exe()
        .ok()
        .and_then(|p| p.parent().map(|d| d.join(імʼя())));

    if let Some(p) = поруч
        && p.is_file()
    {
        return Some(p);
    }

    let path = std::env::var_os("PATH")?;
    std::env::split_paths(&path)
        .map(|d| d.join(імʼя()))
        .find(|p| p.is_file())
}

fn імʼя() -> &'static str {
    if cfg!(windows) { "ffmpeg.exe" } else { "ffmpeg" }
}

/// Перекласти потік в інший контейнер, не чіпаючи самих даних.
///
/// Потрібно там, де сегменти склеїлись у `.ts`, а людина просила `.mp4`:
/// вміст той самий, але з нормальним контейнером файл перемотується й
/// відкривається будь-де.
pub async fn змінити_контейнер(звідки: &Path, куди: &Path) -> Результат<()> {
    виконати(&[
        "-i".as_ref(),
        звідки.as_os_str(),
        "-c".as_ref(),
        "copy".as_ref(),
        // Потік із HLS часто має «сміттєві» службові доріжки; беремо лише
        // те, що справді відтворюється.
        "-map".as_ref(),
        "0:v?".as_ref(),
        "-map".as_ref(),
        "0:a?".as_ref(),
        куди.as_os_str(),
    ])
    .await
}

/// Звести відео зі звуком в один файл.
///
/// DASH і YouTube роздають доріжки окремо — без цього кроку в людини
/// лишаються два файли, жоден з яких не є тим, що вона просила.
pub async fn звести(відео: &Path, звук: &Path, куди: &Path) -> Результат<()> {
    виконати(&[
        "-i".as_ref(),
        відео.as_os_str(),
        "-i".as_ref(),
        звук.as_os_str(),
        "-c".as_ref(),
        "copy".as_ref(),
        "-map".as_ref(),
        "0:v:0".as_ref(),
        "-map".as_ref(),
        "1:a:0".as_ref(),
        куди.as_os_str(),
    ])
    .await
}

/// Спільна частина: запустити ffmpeg і зрозуміло розповісти про невдачу.
async fn виконати(аргументи: &[&std::ffi::OsStr]) -> Результат<()> {
    let Some(exe) = знайти() else {
        return Err(Помилка::Немає);
    };

    let out = Command::new(&exe)
        // `-y` — переписати ціль: інакше ffmpeg зупиняється й **чекає на
        // відповідь у консолі**, а ми його виводу не читаємо. Завдання
        // зависло б назавжди, і причина була б невидима.
        .arg("-y")
        .arg("-hide_banner")
        .arg("-loglevel")
        .arg("error")
        .args(аргументи)
        .output()
        .await
        .map_err(|e| Помилка::Запуск(format!("{}: {e}", exe.display())))?;

    if out.status.success() {
        return Ok(());
    }

    let текст = String::from_utf8_lossy(&out.stderr);
    let останній = текст
        .lines()
        .rev()
        .find(|l| !l.trim().is_empty())
        .unwrap_or("без пояснення");

    Err(Помилка::Відмова(останній.to_owned()))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn імʼя_залежить_від_системи() {
        if cfg!(windows) {
            assert_eq!(імʼя(), "ffmpeg.exe");
        } else {
            assert_eq!(імʼя(), "ffmpeg");
        }
    }

    /// ⚠️ Текст цієї помилки бачить людина, і він мусить казати, що робити.
    /// «ffmpeg не знайдено» без продовження лишає її наодинці з проблемою.
    #[test]
    fn відсутній_ffmpeg_каже_що_робити() {
        let текст = Помилка::Немає.to_string();
        assert!(текст.contains("ffmpeg-install"), "{текст}");
    }

    /// ⚠️ Пошук мусить віддавати перевагу **нашому** ffmpeg — тому, що
    /// поруч із програмою. Чужий із PATH може бути зібраний без потрібних
    /// форматів, і тоді зведення падало б на рівному місці.
    #[test]
    fn поруч_важливіше_за_path() {
        let поруч = std::env::current_exe()
            .ok()
            .and_then(|p| p.parent().map(|d| d.join(імʼя())));

        let Some(поруч) = поруч else {
            return;
        };

        if !поруч.is_file() {
            // Поруч його немає — перевіряти пріоритет ні на чому.
            return;
        }

        assert_eq!(
            знайти().as_deref(),
            Some(поруч.as_path()),
            "коли ffmpeg лежить поруч, беремо саме його"
        );
    }
}
